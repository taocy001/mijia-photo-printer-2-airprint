from io import BytesIO
import struct
import random
import unittest
from PIL import Image
from offline import (Attribute, Message, CANVAS, TARGET_BYTES, Unsupported,
                     prepare_jpeg, job_model, encode_ipp, decode_ipp,
                     offline_response, prepare_ipp_fixture)
from offline import encode_inner_upload_chunk


def jpeg(image, **kwargs):
    out = BytesIO()
    image.save(out, "JPEG", quality=95, **kwargs)
    return out.getvalue()


class ImageTests(unittest.TestCase):
    def test_fit_rotates_landscape_to_match_paper(self):
        result = prepare_jpeg(jpeg(Image.new("RGB", (600, 400), "red")), scaling="fit")
        with Image.open(BytesIO(result.jpeg)) as im:
            self.assertEqual(im.size, CANVAS)
            self.assertEqual(im.mode, "RGB")
            self.assertLess(im.getpixel((50, 50))[1], 10)
            self.assertLess(im.getpixel((600, 900))[1], 10)
            self.assertIn("icc_profile", im.info)
        self.assertLessEqual(len(result.jpeg), TARGET_BYTES)

    def test_exif_orientation_and_optional_180_rotation(self):
        im = Image.new("RGB", (600, 400), "blue")
        im.paste("red", (0, 0, 300, 400))
        exif = Image.Exif(); exif[274] = 6
        data = jpeg(im, exif=exif)
        normal = prepare_jpeg(data)
        flipped = prepare_jpeg(data, rotate_180=True)
        with Image.open(BytesIO(normal.jpeg)) as a, Image.open(BytesIO(flipped.jpeg)) as b:
            self.assertGreater(a.getpixel((600, 100))[0], 240)
            self.assertGreater(b.getpixel((600, 100))[2], 240)
            self.assertNotIn(274, a.getexif())

    def test_quality_search_and_bounded_file(self):
        # Deterministic fine detail: quality 100 exceeds the target.
        noise = random.Random(42).randbytes(CANVAS[0]*CANVAS[1])
        pixels = bytes(112+(v % 32) for v in noise)
        im = Image.frombytes("L", CANVAS, pixels).convert("RGB")
        result = prepare_jpeg(jpeg(im))
        self.assertTrue(60 <= result.quality < 100)
        self.assertLessEqual(len(result.jpeg), TARGET_BYTES)

    def test_non_jpeg_and_oc_fail_explicitly(self):
        with self.assertRaises(Unsupported):
            prepare_jpeg(b"%PDF-1.7\n")
        prepared = prepare_jpeg(jpeg(Image.new("RGB", CANVAS, "white")))
        with self.assertRaises(Unsupported):
            job_model(prepared, oc=b"unverified")
        plan = job_model(prepared, copies=2)
        self.assertEqual(plan["params"]["file-size"], len(prepared.jpeg))
        self.assertEqual(plan["params"]["media-size"], 5012)
        self.assertEqual(plan["params"]["channel"], 64256)
        self.assertFalse(plan["ready-to-send"])
        self.assertIsNone(plan["usb-frame"])


class IppTests(unittest.TestCase):
    def test_independent_wire_fixture_and_binary_document(self):
        # Handcrafted IPP/2.0 request, not generated by the encoder under test.
        raw = bytes.fromhex("020000020000002a01470012617474726962757465732d6368617273657400057574662d3803")
        raw += b"\xff\xd8\x03\x00\xff\xd9"
        msg = decode_ipp(raw)
        self.assertEqual(msg.request_id, 42)
        self.assertEqual(msg.values("attributes-charset"), [b"utf-8"])
        self.assertEqual(msg.document, b"\xff\xd8\x03\x00\xff\xd9")
        self.assertEqual(encode_ipp(msg), raw)

    def test_truncation_continuation_and_collection_rejected(self):
        for raw in [b"", bytes.fromhex("02000002000000010149000000017803"),
                    bytes.fromhex("020000020000000101490004616203"),
                    bytes.fromhex("020000020000000101340000000003")]:
            with self.assertRaises(Unsupported): decode_ipp(raw)

    def test_offline_never_accepts_job(self):
        req = Message((2, 0), 2, 77, ())
        response = decode_ipp(offline_response(encode_ipp(req)))
        self.assertEqual(response.code, 0x0502)
        self.assertEqual(response.request_id, 77)
        self.assertEqual(response.values("job-id"), [])
        attrs = decode_ipp(offline_response(encode_ipp(Message((2, 0), 11, 5, ()))))
        self.assertEqual(attrs.values("printer-is-accepting-jobs"), [b"\0"])
        self.assertEqual(attrs.values("document-format-supported"), [b"image/jpeg"])

    def test_print_fixture_becomes_model_without_transport(self):
        attrs = (Attribute(1, 0x49, "document-format", b"image/jpeg"),
                 Attribute(2, 0x21, "copies", struct.pack(">i", 2)),
                 Attribute(2, 0x44, "media", b"na_index-4x6_4x6in"))
        raw = encode_ipp(Message((2, 0), 2, 8, attrs,
                                jpeg(Image.new("RGB", (800, 1200), "green"))))
        prepared, plan = prepare_ipp_fixture(raw)
        self.assertEqual(prepared.size, CANVAS)
        self.assertEqual(plan["params"]["copies"], 2)
        self.assertFalse(plan["ready-to-send"])

    def test_unsupported_ipp_options_are_not_silently_accepted(self):
        image = jpeg(Image.new("RGB", (100, 150), "white"))
        base = [Attribute(1, 0x49, "document-format", b"image/jpeg")]
        for extra in [Attribute(2, 0x44, "media", b"iso_a4_210x297mm"),
                      Attribute(2, 0x44, "sides", b"two-sided-long-edge"),
                      Attribute(2, 0x21, "copies", struct.pack(">i", -1))]:
            raw = encode_ipp(Message((2, 0), 2, 1, tuple(base+[extra]), image))
            with self.assertRaises(Unsupported): prepare_ipp_fixture(raw)


class UploadBufferTests(unittest.TestCase):
    def test_inner_buffer_length_job_id_endianness_and_binary_payload(self):
        self.assertEqual(encode_inner_upload_chunk(b"\xff\xd8\x00\x0a", 0x01020304),
                         b"cmd data EXTLEN=8\n\x04\x03\x02\x01\xff\xd8\x00\x0a")
        block = encode_inner_upload_chunk(b"x"*8192, 1)
        self.assertTrue(block.startswith(b"cmd data EXTLEN=8196\n"))
        for data, jid in [(b"", 1), (b"x"*8193, 1), (b"x", 0), (b"x", 2**31)]:
            with self.assertRaises(Unsupported): encode_inner_upload_chunk(data, jid)


